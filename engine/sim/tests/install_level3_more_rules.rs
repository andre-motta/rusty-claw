#[test]
fn install_level3_boost_route_respawn_enemy_moves_rat_touch_and_limits() {
    let Some(level) = level(3) else { return };
    let script = route(BOOST_ROUTE, 12240);
    let mut sim = Sim::new(level, config(LEVEL3_RNG_AT_T0));
    // The serial numbers the game gives the pacing cutthroat by the
    // checkpoint and the rat below it.
    let (cutthroat, rat) = (207, 836);
    let mut checked = false;
    for (tick, t) in script.ticks.iter().enumerate() {
        let snap = sim.step(*t);
        check_rng(&sim, &BOOST_RNG, tick);
        let claw = sim.player().expect("Claw").clone();
        let health = sim.stats().health;
        match tick {
            // Rules 2, 3 and 5: the respawn after the death in tick 7896.
            7896 => {
                assert!(snap.events.contains(&GameEvent::ClawDied { lives_left: 5 }));
                assert_eq!(enemy_at(&mut sim, cutthroat).1, 17625);
            }
            7897 => {
                assert_eq!(
                    (claw.x, claw.y, claw.state),
                    (17030, 7247, state::MOVE_LEFT)
                );
                assert_eq!(sim.camera().current, (17286, 7363), "no jump");
                let (st, x, _) = enemy_at(&mut sim, cutthroat);
                assert_eq!((st, x), (Some(EnemyState::Pace), 17627), "one move");
            }
            // Rule 7: the rat turns on its exact limit.
            8008 => {
                let (st, x, exact) = enemy_at(&mut sim, rat);
                assert_eq!((st, x), (Some(EnemyState::MoveLeft), 17328));
                assert!((exact - 17328.52).abs() < 1e-6, "{exact}");
            }
            8009 => {
                let (st, x, exact) = enemy_at(&mut sim, rat);
                assert_eq!((st, x, exact), (Some(EnemyState::MoveLeft), 17328, 17328.0));
            }
            8010 => {
                let (st, x, _) = enemy_at(&mut sim, rat);
                assert_eq!((st, x), (Some(EnemyState::MoveRight), 17329), "turned");
            }
            // Rule 6: the rat's touch at its position.
            10687 | 10689 => {
                assert_eq!(by_serial(&sim, rat).1.attack_rect, enemy::rat::TOUCH_BOX);
                assert_eq!(at_of(by_serial(&sim, rat).1), (17357, 8042));
                assert_eq!((health, claw.state), (65, state::FALL), "not hit yet");
            }
            10690 => {
                assert_eq!((claw.x, claw.y, health), (17370, 7997, 60), "hit");
            }
            // Rule 7's later bomb.
            12232 => assert_eq!(health, 70),
            12233 => {
                assert_eq!((claw.x, claw.y, health), (17157, 8015, 55), "the bomb");
                checked = true;
            }
            _ => {}
        }
    }
    assert!(checked);
}

